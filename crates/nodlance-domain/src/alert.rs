//! Alerts, notifications, and maintenance windows.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Severity of an alert rule or incident.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AlertSeverity {
    Info,
    Warning,
    Critical,
}

impl AlertSeverity {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Info => "info",
            Self::Warning => "warning",
            Self::Critical => "critical",
        }
    }
}

/// Lifecycle state of an alert incident.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AlertStatus {
    Firing,
    Acknowledged,
    Resolved,
}

impl AlertStatus {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Firing => "firing",
            Self::Acknowledged => "acknowledged",
            Self::Resolved => "resolved",
        }
    }
}

/// An alert evaluation rule.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AlertRule {
    pub id: Uuid,
    pub name: String,
    pub condition: String,
    pub severity: AlertSeverity,
    pub is_enabled: bool,
    pub created_at: DateTime<Utc>,
}

/// An incident generated by a triggered alert rule.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AlertIncident {
    pub id: Uuid,
    pub rule_id: Option<Uuid>,
    pub title: String,
    pub description: String,
    pub severity: AlertSeverity,
    pub status: AlertStatus,
    pub resource_type: String,
    pub resource_id: Option<Uuid>,
    pub fired_at: DateTime<Utc>,
    pub acknowledged_at: Option<DateTime<Utc>>,
    pub resolved_at: Option<DateTime<Utc>>,
}

/// A planned maintenance window during which alerts for specified resources are suppressed.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MaintenanceWindow {
    pub id: Uuid,
    pub title: String,
    pub starts_at: DateTime<Utc>,
    pub ends_at: DateTime<Utc>,
    pub resource_type: Option<String>,
    pub resource_id: Option<Uuid>,
    pub created_at: DateTime<Utc>,
}

/// Input for creating a new maintenance window.
#[derive(Debug, Deserialize)]
pub struct NewMaintenanceWindow {
    pub title: String,
    pub starts_at: DateTime<Utc>,
    pub ends_at: DateTime<Utc>,
    pub resource_type: Option<String>,
    pub resource_id: Option<Uuid>,
}
