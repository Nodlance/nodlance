//! Linux/VM guarded provisioning provider with preflight checks, config templating, and rollback.

use nodlance_domain::{
    DatabaseEngine, DomainError, ProvisioningConfig, ProvisioningPlan, ProvisioningStepType,
};
use serde::{Deserialize, Serialize};
use std::path::Path;

#[derive(Debug, thiserror::Error)]
pub enum LinuxProviderError {
    #[error("preflight check failed: {0}")]
    PreflightFailed(String),
    #[error("configuration error: {0}")]
    Config(String),
    #[error("unsupported engine/version: {0}")]
    UnsupportedVersion(String),
    #[error("io error: {0}")]
    Io(String),
}

impl From<LinuxProviderError> for DomainError {
    fn from(err: LinuxProviderError) -> Self {
        match err {
            LinuxProviderError::PreflightFailed(msg) => DomainError::Validation(msg),
            LinuxProviderError::UnsupportedVersion(msg) => DomainError::Validation(msg),
            LinuxProviderError::Config(msg) => DomainError::Validation(msg),
            LinuxProviderError::Io(msg) => DomainError::Internal(msg),
        }
    }
}

/// Diagnostic report generated by preflight environment validation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LinuxPreflightReport {
    pub is_valid: bool,
    pub errors: Vec<String>,
    pub warnings: Vec<String>,
}

/// Evaluates host and plan pre-conditions before mutating any system state.
pub fn validate_linux_preflight(plan: &ProvisioningPlan) -> LinuxPreflightReport {
    let mut errors = Vec::new();
    let mut warnings = Vec::new();

    // 1. Engine & Version Compatibility Gate
    match plan.engine {
        DatabaseEngine::PostgreSql => {
            let major = plan
                .engine_version
                .split('.')
                .next()
                .and_then(|v| v.parse::<u32>().ok())
                .unwrap_or(0);
            if !(13..=18).contains(&major) {
                errors.push(format!(
                    "PostgreSQL version '{}' is not supported (supported: 13..=18)",
                    plan.engine_version
                ));
            }
        }
        DatabaseEngine::MySql => {
            if !plan.engine_version.starts_with("8.0") && !plan.engine_version.starts_with("8.4") {
                errors.push(format!(
                    "MySQL version '{}' is not supported (supported: 8.0, 8.4)",
                    plan.engine_version
                ));
            }
        }
        DatabaseEngine::MariaDb => {
            warnings.push("MariaDB compatibility is experimental in Linux provider".to_string());
        }
    }

    // 2. Data directory validation
    if let Some(dir) = &plan.config.data_directory {
        let p = Path::new(dir);
        if !p.is_absolute() {
            errors.push(format!("data_directory must be an absolute path: '{dir}'"));
        } else if dir == "/"
            || dir.starts_with("/bin")
            || dir.starts_with("/boot")
            || dir.starts_with("/dev")
            || dir.starts_with("/etc")
            || dir.starts_with("/lib")
            || dir.starts_with("/sys")
            || dir.starts_with("/usr")
        {
            errors.push(format!(
                "data_directory cannot be in system critical paths: '{dir}'"
            ));
        }
    } else {
        warnings.push("No data_directory specified, provider default will be used".to_string());
    }

    // 3. Port validation
    if let Some(port) = plan.config.port {
        if port == 0 {
            errors.push("port cannot be 0".to_string());
        } else if port < 1024 && port != 5432 && port != 3306 {
            warnings.push(format!("port {port} is in privileged range (< 1024)"));
        }
    }

    // 4. Memory buffer check
    if let (Some(shared), Some(total)) =
        (plan.config.shared_buffers_mb, plan.config.memory_limit_mb)
    {
        if shared >= total {
            errors.push(format!(
                "shared_buffers_mb ({shared}) cannot exceed memory_limit_mb ({total})"
            ));
        }
    }

    LinuxPreflightReport {
        is_valid: errors.is_empty(),
        errors,
        warnings,
    }
}

/// Generates hardened database engine configuration files.
pub struct LinuxConfigGenerator;

impl LinuxConfigGenerator {
    pub fn generate_postgres_conf(config: &ProvisioningConfig) -> String {
        let port = config.port.unwrap_or(5432);
        let max_connections = config.max_connections.unwrap_or(100);
        let shared_buffers = config.shared_buffers_mb.unwrap_or(256);

        format!(
            "# Nodlance Generated postgresql.conf\n\
            listen_addresses = '*'\n\
            port = {port}\n\
            max_connections = {max_connections}\n\
            shared_buffers = {shared_buffers}MB\n\
            ssl = on\n\
            password_encryption = scram-sha-256\n\
            shared_preload_libraries = ''\n\
            log_destination = 'stderr'\n\
            logging_collector = on\n\
            log_line_prefix = '%m [%p] %u@%d '\n\
            "
        )
    }

    pub fn generate_pg_hba_conf() -> String {
        "# Nodlance Generated pg_hba.conf\n\
        # TYPE  DATABASE        USER            ADDRESS                 METHOD\n\
        local   all             all                                     peer\n\
        host    all             all             127.0.0.1/32            scram-sha-256\n\
        host    all             all             ::1/128                 scram-sha-256\n\
        host    all             all             0.0.0.0/0               scram-sha-256\n\
        "
        .to_string()
    }

    pub fn generate_mysql_cnf(config: &ProvisioningConfig) -> String {
        let port = config.port.unwrap_or(3306);
        let max_connections = config.max_connections.unwrap_or(150);
        let buffer_pool = config.shared_buffers_mb.unwrap_or(256);

        format!(
            "# Nodlance Generated my.cnf\n\
            [mysqld]\n\
            bind-address = 0.0.0.0\n\
            port = {port}\n\
            max_connections = {max_connections}\n\
            innodb_buffer_pool_size = {buffer_pool}M\n\
            default_authentication_plugin = caching_sha2_password\n\
            character-set-server = utf8mb4\n\
            collation-server = utf8mb4_unicode_ci\n\
            "
        )
    }
}

/// Generates isolated systemd unit configurations for Linux environments.
pub struct LinuxSystemdGenerator;

impl LinuxSystemdGenerator {
    pub fn generate_unit(
        engine: DatabaseEngine,
        service_name: &str,
        data_dir: &str,
        user: &str,
    ) -> String {
        let exec_cmd = match engine {
            DatabaseEngine::PostgreSql => format!("/usr/lib/postgresql/bin/postgres -D {data_dir}"),
            DatabaseEngine::MySql | DatabaseEngine::MariaDb => {
                format!("/usr/sbin/mysqld --datadir={data_dir}")
            }
        };

        format!(
            "[Unit]\n\
            Description=Nodlance Managed {engine:?} Database Server ({service_name})\n\
            After=network.target\n\n\
            [Service]\n\
            Type=simple\n\
            User={user}\n\
            Group={user}\n\
            ExecStart={exec_cmd}\n\
            Restart=on-failure\n\
            RestartSec=5s\n\
            TimeoutSec=300\n\
            LimitNOFILE=65536\n\
            UMask=0077\n\n\
            [Install]\n\
            WantedBy=multi-user.target\n\
            "
        )
    }
}

/// Computes reverse compensation steps for least-privilege rollback.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum LinuxRollbackAction {
    StopService(String),
    PurgeDataDirectory(String),
    RemoveConfigFile(String),
    CleanStorage(String),
}

pub struct LinuxRollbackPlanner;

impl LinuxRollbackPlanner {
    pub fn plan_rollback(
        plan: &ProvisioningPlan,
        completed_steps: &[ProvisioningStepType],
    ) -> Vec<LinuxRollbackAction> {
        let mut actions = Vec::new();
        let service_name = format!("{}-{}", plan.engine.as_str(), plan.id);
        let data_dir = plan
            .config
            .data_directory
            .clone()
            .unwrap_or_else(|| format!("/var/lib/nodlance/{}", plan.id));

        // Iterate in reverse (LIFO)
        for step in completed_steps.iter().rev() {
            match step {
                ProvisioningStepType::StartService | ProvisioningStepType::VerifyReadiness => {
                    actions.push(LinuxRollbackAction::StopService(service_name.clone()));
                }
                ProvisioningStepType::InitializeDatabase => {
                    actions.push(LinuxRollbackAction::PurgeDataDirectory(data_dir.clone()));
                }
                ProvisioningStepType::RenderConfiguration => {
                    actions.push(LinuxRollbackAction::RemoveConfigFile(format!(
                        "/etc/nodlance/{}.conf",
                        plan.id
                    )));
                }
                ProvisioningStepType::PrepareStorage => {
                    actions.push(LinuxRollbackAction::CleanStorage(data_dir.clone()));
                }
                ProvisioningStepType::PreflightCheck => {}
            }
        }

        actions
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use nodlance_domain::{ProviderType, ProvisioningStatus};
    use uuid::Uuid;

    fn sample_plan(engine: DatabaseEngine, version: &str) -> ProvisioningPlan {
        ProvisioningPlan {
            id: Uuid::now_v7(),
            cluster_id: Uuid::now_v7(),
            host_id: Some(Uuid::now_v7()),
            provider_type: ProviderType::LinuxVm,
            engine,
            engine_version: version.to_string(),
            config: ProvisioningConfig {
                port: Some(5432),
                data_directory: Some("/var/lib/postgresql/data".to_string()),
                max_connections: Some(100),
                shared_buffers_mb: Some(256),
                memory_limit_mb: Some(1024),
                cpu_limit_cores: Some(2.0),
                container_image: None,
                namespace: None,
                extra_params: None,
            },
            status: ProvisioningStatus::Pending,
            created_at: chrono::Utc::now(),
            updated_at: chrono::Utc::now(),
        }
    }

    #[test]
    fn test_valid_postgres_preflight() {
        let plan = sample_plan(DatabaseEngine::PostgreSql, "16.1");
        let report = validate_linux_preflight(&plan);
        assert!(report.is_valid);
        assert!(report.errors.is_empty());
    }

    #[test]
    fn test_invalid_postgres_version() {
        let plan = sample_plan(DatabaseEngine::PostgreSql, "11.2");
        let report = validate_linux_preflight(&plan);
        assert!(!report.is_valid);
        assert!(report.errors[0].contains("not supported"));
    }

    #[test]
    fn test_invalid_system_path() {
        let mut plan = sample_plan(DatabaseEngine::PostgreSql, "16.1");
        plan.config.data_directory = Some("/usr/bin/data".to_string());
        let report = validate_linux_preflight(&plan);
        assert!(!report.is_valid);
        assert!(report.errors[0].contains("system critical paths"));
    }

    #[test]
    fn test_config_generation() {
        let plan = sample_plan(DatabaseEngine::PostgreSql, "16.1");
        let conf = LinuxConfigGenerator::generate_postgres_conf(&plan.config);
        assert!(conf.contains("listen_addresses = '*'"));
        assert!(conf.contains("port = 5432"));
        assert!(conf.contains("shared_buffers = 256MB"));

        let hba = LinuxConfigGenerator::generate_pg_hba_conf();
        assert!(hba.contains("scram-sha-256"));
    }

    #[test]
    fn test_rollback_ordering_is_lifo() {
        let plan = sample_plan(DatabaseEngine::PostgreSql, "16.1");
        let executed = [
            ProvisioningStepType::PreflightCheck,
            ProvisioningStepType::PrepareStorage,
            ProvisioningStepType::RenderConfiguration,
            ProvisioningStepType::InitializeDatabase,
            ProvisioningStepType::StartService,
        ];

        let rollback = LinuxRollbackPlanner::plan_rollback(&plan, &executed);
        assert_eq!(rollback.len(), 4);
        assert!(matches!(rollback[0], LinuxRollbackAction::StopService(_)));
        assert!(matches!(
            rollback[1],
            LinuxRollbackAction::PurgeDataDirectory(_)
        ));
        assert!(matches!(
            rollback[2],
            LinuxRollbackAction::RemoveConfigFile(_)
        ));
        assert!(matches!(rollback[3], LinuxRollbackAction::CleanStorage(_)));
    }
}
